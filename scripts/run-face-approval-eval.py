def threshold_sweep(genuine_scores: list[float], impostor_scores: list[float]) -> tuple[list[dict[str, Any]], float | None]:
    rows: list[dict[str, Any]] = []
    best: tuple[float, float] | None = None
    for step in range(0, 201):
        threshold = step / 200
        far = (
            sum(score >= threshold for score in impostor_scores) / len(impostor_scores)
            if impostor_scores
            else 0
        )
        frr = (
            sum(score < threshold for score in genuine_scores) / len(genuine_scores)
            if genuine_scores
            else 0
        )
        row = {
            "threshold": round(threshold, 3),
            "false_accept_rate": round(far, 6),
            "false_reject_rate": round(frr, 6),
        }
        rows.append(row)
        gap = abs(far - frr)
        eer = (far + frr) / 2
        if best is None or gap < best[0]:
            best = (gap, eer)
    return rows, round(best[1], 6) if best else None


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fieldnames = sorted({key for row in rows for key in row.keys()})
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def read_csv_rows(path: Path) -> list[dict[str, Any]]:
    if not path.exists() or path.stat().st_size == 0:
        return []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def run_artifact_path(run_dir: Path, filename: str) -> Path | None:
    for candidate in (run_dir / filename, run_dir / "review" / filename):
        if candidate.exists():
            return candidate
    if filename == "case-review.csv":
        candidate = run_dir / "review" / "cases.csv"
        if candidate.exists():
            return candidate
    return None


def load_run_json(run_dir: Path, filename: str) -> dict[str, Any]:
    path = run_artifact_path(run_dir, filename)
    if path is None:
        raise FileNotFoundError(f"Run artifact not found: {run_dir / filename}")
    return load_json(path)


def load_run_approval(run_dir: Path) -> dict[str, Any]:
    approval_path = run_artifact_path(run_dir, "approval.json")
    if approval_path is not None:
        return load_json(approval_path)
    gates_path = run_artifact_path(run_dir, "approval-gates.csv")
    if gates_path is None:
        raise FileNotFoundError(f"Run approval gates not found: {run_dir / 'approval-gates.csv'}")
    gates = read_csv_rows(gates_path)
    normalized = []
    approved = True
    for gate in gates:
        passed = str(gate.get("passed", "")).lower() == "true"
        approved = approved and passed
        normalized.append(
            {
                "metric": gate.get("metric"),
                "actual": gate.get("actual"),
                "comparator": gate.get("comparator"),
                "expected": gate.get("expected"),
                "passed": passed,
            }
        )
    return {"approved": approved, "gates": normalized}


def read_run_csv(run_dir: Path, *filenames: str) -> list[dict[str, Any]]:
    for filename in filenames:
        path = run_artifact_path(run_dir, filename)
        if path is not None:
            return read_csv_rows(path)
    return []


def resolve_case_image_path(path_value: Any) -> Path | None:
    value = str(path_value or "").strip()
    if not value:
        return None
    path = Path(value)
    if path.is_absolute():
        return path
    return (ROOT / path).resolve()


def image_key(path_value: Any) -> str:
    path = resolve_case_image_path(path_value)
    if path is None:
        return str(path_value or "")
    try:
        return path.resolve().as_posix().lower()
    except OSError:
        return path.as_posix().lower()


def parse_boxes(value: Any) -> list[list[int]]:
    if not value:
        return []
    try:
        boxes = json.loads(str(value))
    except (TypeError, json.JSONDecodeError):
        return []
    if not isinstance(boxes, list):
        return []
    normalized: list[list[int]] = []
    for box in boxes:
        if isinstance(box, list) and len(box) == 4:
            try:
                normalized.append([int(float(item)) for item in box])
            except (TypeError, ValueError):
                continue
    return normalized


def overlay_boxes_for_run(run_dir: Path, metrics: dict[str, Any]) -> dict[str, dict[str, list[list[int]]]]:
    kind = metrics.get("dataset", {}).get("kind")
    overlays: dict[str, dict[str, list[list[int]]]] = {}
    if kind == "identity-face-eval":
        for row in read_run_csv(run_dir, "extractions.csv"):
            boxes = parse_boxes(f"[{row.get('bbox')}]" if row.get("bbox") else "")
            if boxes:
                overlays[image_key(row.get("path"))] = {"predicted": boxes}
    elif kind == "wider-face-detection-eval":
        for row in read_run_csv(run_dir, "wider-detection-summary.csv"):
            overlays[image_key(row.get("path"))] = {
                "ground_truth": parse_boxes(row.get("ground_truth_bboxes")),
                "predicted": parse_boxes(row.get("predicted_bboxes")),
            }
    return overlays


def draw_scaled_boxes(
    draw: ImageDraw.ImageDraw,
    boxes: list[list[int]],
    scale_x: float,
    scale_y: float,
    color: str,
) -> None:
    for box in boxes:
        x1, y1, x2, y2 = box
        scaled = [x1 * scale_x, y1 * scale_y, x2 * scale_x, y2 * scale_y]
        draw.rectangle(scaled, outline=color, width=3)


def write_review_thumbnail(source: Path, target: Path, overlays: dict[str, list[list[int]]]) -> bool:
    if not source.exists() or not source.is_file():
        return False
    try:
        with Image.open(source) as image:
            original_width, original_height = image.size
            preview = image.convert("RGB")
            preview.thumbnail(THUMBNAIL_SIZE, RESAMPLE_LANCZOS)
            scale_x = preview.width / max(1, original_width)
            scale_y = preview.height / max(1, original_height)
            draw = ImageDraw.Draw(preview)
            draw_scaled_boxes(draw, overlays.get("ground_truth", []), scale_x, scale_y, "#16a34a")
            draw_scaled_boxes(draw, overlays.get("predicted", []), scale_x, scale_y, "#05AD98")
            target.parent.mkdir(parents=True, exist_ok=True)
            preview.save(target, format="JPEG", quality=82, optimize=True)
        return True
    except Exception:
        return False


def case_review_rows_for_run(run_dir: Path, metrics: dict[str, Any]) -> list[dict[str, Any]]:
    existing_rows = read_run_csv(run_dir, "case-review.csv", "cases.csv")
    if existing_rows:
        return existing_rows
    kind = metrics.get("dataset", {}).get("kind")
    if kind == "identity-face-eval":
        return identity_case_review_rows(
            read_run_csv(run_dir, "extractions.csv"),
            read_run_csv(run_dir, "probe-predictions.csv"),
        )
    if kind == "group-e2e":
        return group_case_review_rows(read_run_csv(run_dir, "group-detection-summary.csv"))
    if kind == "wider-face-detection-eval":
        return wider_case_review_rows(read_run_csv(run_dir, "wider-detection-summary.csv"))
    return []


def rows_with_review_photos(
    review_dir: Path,
    rows: list[dict[str, Any]],
    overlays: dict[str, dict[str, list[list[int]]]],
) -> list[dict[str, Any]]:
    photos_dir = review_dir / "photos"
    photo_by_source: dict[str, str] = {}
    enriched: list[dict[str, Any]] = []
    for index, row in enumerate(rows, start=1):
        copy = dict(row)
        source = resolve_case_image_path(row.get("path"))
        source_key = image_key(row.get("path"))
        if source is not None:
            if source_key not in photo_by_source:
                image_id = slugify_filename(str(row.get("image_id") or source.stem), 72)
                target = photos_dir / f"{len(photo_by_source) + 1:04d}-{image_id}.jpg"
                if write_review_thumbnail(source, target, overlays.get(source_key, {})):
                    photo_by_source[source_key] = target.relative_to(review_dir).as_posix()
                else:
                    photo_by_source[source_key] = ""
            copy["photo"] = photo_by_source[source_key]
        else:
            copy["photo"] = ""
        copy["case_number"] = index
        enriched.append(copy)
    return enriched


def status_counts(rows: list[dict[str, Any]]) -> dict[str, int]:
    counts = {"PASS": 0, "PARTIAL": 0, "FAIL": 0}
    for row in rows:
        status = str(row.get("status") or "").upper()
        if status in counts:
            counts[status] += 1
    return counts


def flatten_metrics(value: Any, prefix: str = "") -> list[tuple[str, str]]:
    if isinstance(value, dict):
        flattened: list[tuple[str, str]] = []
        for key, nested in value.items():
            next_prefix = f"{prefix}.{key}" if prefix else str(key)
            flattened.extend(flatten_metrics(nested, next_prefix))
        return flattened
    if isinstance(value, list):
        return [(prefix, json.dumps(value))]
    return [(prefix, "" if value is None else str(value))]


def html_table(headers: list[str], rows: list[dict[str, Any]]) -> str:
    body = []
    for row in rows:
        body.append(
            "<tr>"
            + "".join(f"<td>{html.escape(str(row.get(header, '')))}</td>" for header in headers)
            + "</tr>"
        )
    return (
        "<table><thead><tr>"
        + "".join(f"<th>{html.escape(header)}</th>" for header in headers)
        + "</tr></thead><tbody>"
        + "\n".join(body)
        + "</tbody></table>"
    )


