def compact_run_dir(run_dir: Path) -> None:
    for child in run_dir.iterdir():
        if child.name in {"README.md", "review"}:
            continue
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()


def prune_review_dir(review_dir: Path) -> None:
    allowed_files = {"index.html", "cases.csv", "metrics.json", "approval-gates.csv"}
    allowed_dirs = {"photos"}
    for child in review_dir.iterdir():
        if child.is_dir():
            if child.name not in allowed_dirs:
                shutil.rmtree(child)
            continue
        if child.name not in allowed_files:
            child.unlink()


def write_review_artifacts(
    run_dir: Path,
    metrics: dict[str, Any],
    approval: dict[str, Any],
    config: dict[str, Any],
    keep_raw: bool = False,
) -> None:
    rows = case_review_rows_for_run(run_dir, metrics)
    overlays = overlay_boxes_for_run(run_dir, metrics)
    review_dir = run_dir / "review"
    if review_dir.exists():
        shutil.rmtree(review_dir)
    review_dir.mkdir(parents=True, exist_ok=True)

    enriched_rows = rows_with_review_photos(review_dir, rows, overlays)
    write_csv(review_dir / "cases.csv", enriched_rows)
    write_json(review_dir / "metrics.json", metrics)
    write_gate_csv(review_dir / "approval-gates.csv", approval)
    (review_dir / "index.html").write_text(review_index_html(metrics, approval, config, enriched_rows), encoding="utf-8")
    prune_review_dir(review_dir)
    (run_dir / "README.md").write_text(run_readme_markdown(metrics, approval, config), encoding="utf-8")

    if not keep_raw:
        compact_run_dir(run_dir)


