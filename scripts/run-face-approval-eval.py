def slugify_filename(value: str, max_length: int = 80) -> str:
    slug = re.sub(r"[^a-zA-Z0-9._-]+", "-", value.strip()).strip("-").lower()
    slug = re.sub(r"-+", "-", slug)
    return (slug or "run")[:max_length].strip("-") or "run"


def manifest_label(manifest_path: Path, manifest: dict[str, Any]) -> str:
    dataset = manifest.get("dataset", {})
    name = dataset.get("name") or manifest_path.stem
    return f"{name}-{manifest_path.stem}"


def default_run_id(config: dict[str, Any], manifest_path: Path, manifest: dict[str, Any]) -> str:
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    profile = slugify_filename(str(config.get("profile") or "eval"), 48)
    manifest_name = slugify_filename(manifest_label(manifest_path, manifest), 48)
    return f"{timestamp}__{profile}__{manifest_name}"


def unique_run_dir(output_root: Path, run_id: str) -> tuple[str, Path]:
    candidate = run_id
    suffix = 2
    while (output_root / candidate).exists():
        candidate = f"{run_id}-{suffix}"
        suffix += 1
    return candidate, output_root / candidate


def unique_target_run_dir(output_root: Path, run_id: str, current_dir: Path) -> tuple[str, Path]:
    candidate = run_id
    suffix = 2
    while (output_root / candidate).exists() and (output_root / candidate).resolve() != current_dir.resolve():
        candidate = f"{run_id}-{suffix}"
        suffix += 1
    return candidate, output_root / candidate


def timestamp_from_run(metrics: dict[str, Any], fallback_name: str) -> str:
    for value in (str(metrics.get("run", {}).get("id") or ""), fallback_name):
        match = re.match(r"^(\d{8}-\d{6})", value)
        if match:
            return match.group(1)
    started_at = str(metrics.get("run", {}).get("started_at") or "")
    if started_at:
        try:
            return datetime.fromisoformat(started_at).strftime("%Y%m%d-%H%M%S")
        except ValueError:
            pass
    return datetime.now().strftime("%Y%m%d-%H%M%S")


def dataset_folder_label(metrics: dict[str, Any]) -> str:
    dataset = metrics.get("dataset", {})
    kind = str(dataset.get("kind") or "dataset")
    if kind == "group-e2e":
        return "group-corpus"
    if kind == "wider-face-detection-eval":
        return "wider-face"
    return str(dataset.get("name") or kind)


def manifest_dataset_folder_label(manifest: dict[str, Any], config: dict[str, Any] | None = None) -> str:
    config = config or {}
    dataset = manifest.get("dataset", {})
    kind = str(manifest.get("kind") or config.get("manifest_kind") or "dataset")
    if kind == "group-e2e":
        return "group-corpus"
    if kind == "wider-face-detection-eval":
        return "wider-face"
    return str(dataset.get("name") or kind)


def readable_run_id(metrics: dict[str, Any], approval: dict[str, Any], fallback_name: str) -> str:
    timestamp = timestamp_from_run(metrics, fallback_name)
    status = slugify_filename(status_text(approval).lower(), 16)
    profile = slugify_filename(str(metrics.get("run", {}).get("profile") or "eval"), 48)
    dataset = slugify_filename(dataset_folder_label(metrics), 48)
    return f"{timestamp}__{status}__{profile}__{dataset}"


def incomplete_run_id(run_dir: Path) -> str:
    match = re.match(r"^(\d{8}-\d{6})", run_dir.name)
    timestamp = match.group(1) if match else run_dir.name
    config_path = run_dir / "approval-config-used.json"
    manifest_path = run_dir / "manifest-used.json"
    config: dict[str, Any] = {}
    manifest: dict[str, Any] = {}
    try:
        config = load_json(config_path) if config_path.exists() else {}
        manifest = load_json(manifest_path) if manifest_path.exists() else {}
    except Exception:
        pass
    profile = slugify_filename(str(config.get("profile") or manifest.get("kind") or "unknown-evaluation"), 48)
    dataset = slugify_filename(manifest_dataset_folder_label(manifest, config) if manifest else "unknown-dataset", 48)
    return f"{timestamp}__incomplete__{profile}__{dataset}"


