def rename_legacy_run_dirs(output_root: Path, keep_raw: bool = False) -> None:
    latest_path = output_root / "latest-run.txt"
    latest_run = latest_path.read_text(encoding="utf-8").strip() if latest_path.exists() else ""
    updated_latest = latest_run

    for run_dir in sorted(path for path in output_root.iterdir() if path.is_dir()):
        is_timestamp_only = re.fullmatch(r"\d{8}-\d{6}", run_dir.name) is not None
        is_incomplete = "__incomplete__" in run_dir.name
        if not is_timestamp_only and not is_incomplete:
            continue
        metrics_path = run_artifact_path(run_dir, "metrics.json")
        approval_path = run_artifact_path(run_dir, "approval.json") or run_artifact_path(run_dir, "approval-gates.csv")
        if metrics_path is None or approval_path is None:
            old_name = run_dir.name
            run_id, renamed_dir = unique_target_run_dir(output_root, incomplete_run_id(run_dir), run_dir)
            if renamed_dir.resolve() != run_dir.resolve():
                run_dir.rename(renamed_dir)
            write_incomplete_review(renamed_dir, keep_raw)
            if latest_run == old_name:
                updated_latest = run_id
            continue
        try:
            metrics = load_json(metrics_path)
            approval = load_run_approval(run_dir)
        except Exception:
            continue

        old_name = run_dir.name
        run_id, renamed_dir = rename_run_dir(output_root, run_dir, metrics, approval)
        updated_metrics_path = run_artifact_path(renamed_dir, "metrics.json") or (renamed_dir / "metrics.json")
        write_json(updated_metrics_path, metrics)
        if latest_run in {old_name, str(metrics.get("run", {}).get("legacy_id") or "")}:
            updated_latest = run_id

    if updated_latest and updated_latest != latest_run:
        latest_path.write_text(updated_latest + "\n", encoding="utf-8")


def backfill_run_review_files(output_root: Path, keep_raw: bool = False) -> None:
    for run_dir in sorted(path for path in output_root.iterdir() if path.is_dir()):
        metrics_path = run_artifact_path(run_dir, "metrics.json")
        approval_path = run_artifact_path(run_dir, "approval.json") or run_artifact_path(run_dir, "approval-gates.csv")
        config_path = run_artifact_path(run_dir, "approval-config-used.json")
        if metrics_path is None or approval_path is None:
            if "__incomplete__" in run_dir.name:
                write_incomplete_review(run_dir, keep_raw)
            continue
        try:
            metrics = load_json(metrics_path)
            approval = load_run_approval(run_dir)
            config = load_json(config_path) if config_path is not None else {"profile": metrics.get("run", {}).get("profile")}
        except Exception:
            continue

        if compact_review_is_complete(run_dir) and not any(
            (run_dir / filename).exists()
            for filename in ("extractions.csv", "group-detection-summary.csv", "wider-detection-summary.csv", "case-review.csv")
        ):
            prune_review_dir(run_dir / "review")
            (run_dir / "README.md").write_text(run_readme_markdown(metrics, approval, config), encoding="utf-8")
            continue

        write_review_artifacts(run_dir, metrics, approval, config, keep_raw)


def evaluation_index_rows(output_root: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for run_dir in sorted((path for path in output_root.iterdir() if path.is_dir()), key=lambda path: path.name):
        metrics_path = run_artifact_path(run_dir, "metrics.json")
        approval_path = run_artifact_path(run_dir, "approval.json") or run_artifact_path(run_dir, "approval-gates.csv")
        if metrics_path is None or approval_path is None:
            if "__incomplete__" in run_dir.name:
                parts = run_dir.name.split("__")
                try:
                    started_at = datetime.strptime(parts[0], "%Y%m%d-%H%M%S").isoformat()
                except (IndexError, ValueError):
                    started_at = run_dir.name
                rows.append(
                    {
                        "run_id": run_dir.name,
                        "folder": run_dir.name,
                        "started_at": started_at,
                        "status": "INCOMPLETE",
                        "profile": parts[2] if len(parts) > 2 else "unknown-evaluation",
                        "manifest": "",
                        "dataset": parts[3] if len(parts) > 3 else "unknown-dataset",
                        "metrics": "run did not finish",
                        "review": (run_dir / "review" / "index.html").exists(),
                        "cases": False,
                        "metrics_json": False,
                        "gates": False,
                    }
                )
            continue
        try:
            metrics = load_json(metrics_path)
            approval = load_run_approval(run_dir)
        except Exception:
            continue
        profile = metrics.get("run", {}).get("profile", run_dir.name)
        rows.append(
            {
                "run_id": metrics.get("run", {}).get("id", run_dir.name),
                "folder": run_dir.name,
                "started_at": metrics.get("run", {}).get("started_at", ""),
                "status": status_text(approval),
                "profile": profile,
                "manifest": metrics.get("run", {}).get("manifest", ""),
                "dataset": dataset_summary(metrics),
                "metrics": key_metric_summary(metrics),
                "review": (run_dir / "review" / "index.html").exists(),
                "cases": (run_dir / "review" / "cases.csv").exists(),
                "metrics_json": (run_dir / "review" / "metrics.json").exists(),
                "gates": (run_dir / "review" / "approval-gates.csv").exists(),
            }
        )
    return sorted(rows, key=lambda row: str(row["started_at"]) or str(row["folder"]), reverse=True)


def write_evaluation_index(output_root: Path, keep_raw: bool = False) -> Path:
    output_root.mkdir(parents=True, exist_ok=True)
    rename_legacy_run_dirs(output_root, keep_raw)
    backfill_run_review_files(output_root, keep_raw)
    rows = evaluation_index_rows(output_root)
    index_path = output_root / "INDEX.md"
    table_rows = []
    for row in rows:
        folder = output_root / str(row["folder"])
        links = []
        if row["review"]:
            links.append(markdown_link(index_path, folder / "review" / "index.html", "visual review"))
        if row["cases"]:
            links.append(markdown_link(index_path, folder / "review" / "cases.csv", "cases csv"))
        if row["metrics_json"]:
            links.append(markdown_link(index_path, folder / "review" / "metrics.json", "metrics json"))
        if row["gates"]:
            links.append(markdown_link(index_path, folder / "review" / "approval-gates.csv", "gates"))
        table_rows.append(
            "| "
            + " | ".join(
                [
                    f"`{row['folder']}`",
                    f"**{row['status']}**",
                    str(row["profile"]),
                    str(row["dataset"]),
                    str(row["metrics"]),
                    ", ".join(links),
                ]
            )
            + " |"
        )

    index_path.write_text(
        """# Face Evaluation Run Index

Open this file first. It maps the run folders to the actual evaluation names, status, datasets, metrics, and visual review report.

## How To Read The Evidence

- `visual review`: one HTML page with all metrics, approval gates, and photo thumbnails.
- `cases csv`: every evaluated photo/case with PASS, PARTIAL, or FAIL.
- `metrics json`: exact metric values.
- `gates`: exact pass/fail approval checks.

## Runs

| Run Folder | Status | Evaluation | Dataset | Main Metrics | Open |
|---|---|---|---|---|---|
"""
        + "\n".join(table_rows)
        + "\n",
        encoding="utf-8",
    )
    write_json(output_root / "INDEX.json", rows)
    return index_path


