def gate_lookup(metrics: dict[str, Any], dotted_key: str) -> Any:
    current: Any = metrics
    for part in dotted_key.split("."):
        if not isinstance(current, dict) or part not in current:
            return None
        current = current[part]
    return current


def evaluate_gates(metrics: dict[str, Any], gates: dict[str, Any]) -> dict[str, Any]:
    results = []
    approved = True
    for key, expected in gates.items():
        actual = gate_lookup(metrics, key)
        if key.split(".")[-1].startswith("min_"):
            passed = actual is not None and actual >= expected
            comparator = ">="
        elif key.split(".")[-1].startswith("max_"):
            passed = actual is not None and actual <= expected
            comparator = "<="
        else:
            passed = actual == expected
            comparator = "=="
        approved = approved and bool(passed)
        results.append(
            {
                "metric": key,
                "actual": actual,
                "comparator": comparator,
                "expected": expected,
                "passed": bool(passed),
            }
        )
    return {"approved": approved, "gates": results}


