def rename_run_dir(
    output_root: Path,
    run_dir: Path,
    metrics: dict[str, Any],
    approval: dict[str, Any],
) -> tuple[str, Path]:
    desired_run_id = readable_run_id(metrics, approval, run_dir.name)
    run_id, target_dir = unique_target_run_dir(output_root, desired_run_id, run_dir)
    run = metrics.setdefault("run", {})
    previous_id = str(run.get("id") or run_dir.name)
    if previous_id != run_id:
        run.setdefault("legacy_id", previous_id)
        run["id"] = run_id
    if target_dir.resolve() != run_dir.resolve():
        run_dir.rename(target_dir)
    return run_id, target_dir


