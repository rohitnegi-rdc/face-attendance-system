def main() -> int:
    args = parse_args()
    output_root = Path(args.output_root).resolve()
    if args.index_only:
        index_path = write_evaluation_index(output_root, args.keep_raw)
        print(json.dumps({"index": str(index_path)}, indent=2))
        return 0

    manifest_path = Path(args.manifest).resolve()
    config_path = Path(args.config).resolve()
    if not manifest_path.exists():
        raise FileNotFoundError(
            f"Manifest not found: {manifest_path}. Build one with scripts/build-face-eval-manifest.py"
        )
    manifest = load_json(manifest_path)
    config = load_json(config_path)
    requested_run_id = args.run_id or default_run_id(config, manifest_path, manifest)
    if args.run_label and not args.run_id:
        requested_run_id = f"{requested_run_id}__{slugify_filename(args.run_label, 48)}"
    run_id, run_dir = unique_run_dir(output_root, requested_run_id)
    run_dir.mkdir(parents=True, exist_ok=True)

    health = check_ai_health(args.ai_url)
    write_json(run_dir / "ai-health.json", health)
    write_json(run_dir / "manifest-used.json", manifest)
    write_json(run_dir / "approval-config-used.json", config)

    manifest_kind = manifest.get("kind") or "group-e2e"
    expected_kind = config.get("manifest_kind")
    if expected_kind and expected_kind != manifest_kind:
        raise ValueError(f"Config expects manifest kind {expected_kind}, got {manifest_kind}")

    if manifest_kind == "identity-face-eval":
        metrics = run_identity_eval(
            manifest, manifest_path, config, run_dir, args.ai_url, run_id, args.limit_identities
        )
    elif manifest_kind == "group-e2e":
        metrics = run_group_eval(manifest, manifest_path, config, run_dir, args.ai_url, run_id, args.limit_photos)
    elif manifest_kind == "wider-face-detection-eval":
        metrics = run_wider_detection_eval(
            manifest, manifest_path, config, run_dir, args.ai_url, run_id, args.limit_photos
        )
    else:
        raise ValueError(f"Unsupported manifest kind: {manifest_kind}")

    approval = evaluate_gates(metrics, config["approval_gates"])
    if not args.run_id:
        run_id, run_dir = rename_run_dir(output_root, run_dir, metrics, approval)
    write_json(run_dir / "metrics.json", metrics)
    write_json(run_dir / "approval.json", approval)
    write_gate_csv(run_dir / "approval-gates.csv", approval)
    (run_dir / "report.md").write_text(report_markdown(metrics, approval, config), encoding="utf-8")
    (run_dir / "README.md").write_text(run_readme_markdown(metrics, approval, config), encoding="utf-8")
    write_review_artifacts(run_dir, metrics, approval, config, args.keep_raw)
    (output_root / "latest-run.txt").write_text(run_id + "\n", encoding="utf-8")
    index_path = write_evaluation_index(output_root, args.keep_raw)

    print(
        json.dumps(
            {
                "run_id": run_id,
                "approved": approval["approved"],
                "profile": config["profile"],
                "output_dir": str(run_dir),
                "index": str(index_path),
                "metrics": metrics,
            },
            indent=2,
        )
    )
    return 1 if args.require_approval and not approval["approved"] else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        print(f"face approval evaluation failed: {error}", file=sys.stderr)
        raise
