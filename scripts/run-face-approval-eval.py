def identity_case_review_rows(
    extraction_rows: list[dict[str, Any]],
    prediction_rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for row in extraction_rows:
        faces_detected = int(row.get("faces_detected") or 0)
        has_embedding = int(row.get("embedding_dimensions") or 0) == 512
        error = row.get("error", "")
        status = "PASS" if faces_detected > 0 and has_embedding and not error else "FAIL"
        reason = "face and embedding extracted" if status == "PASS" else error or "no valid face embedding"
        rows.append(
            {
                "status": status,
                "stage": "face extraction",
                "subject": row.get("identity_label", ""),
                "image_id": row.get("image_id", ""),
                "path": row.get("path", ""),
                "expected": "1 primary face with 512-d embedding",
                "actual": f"{faces_detected} faces, embedding {row.get('embedding_dimensions', '')}",
                "score": "",
                "reason": reason,
            }
        )
    for row in prediction_rows:
        verified = str(row.get("verified_at_threshold")).lower() == "true" or row.get("verified_at_threshold") is True
        top1_correct = str(row.get("top1_correct")).lower() == "true" or row.get("top1_correct") is True
        status = "PASS" if verified else "PARTIAL" if top1_correct else "FAIL"
        reason = (
            "correct identity above threshold"
            if verified
            else "correct identity but below threshold"
            if top1_correct
            else "wrong top-1 identity"
        )
        rows.append(
            {
                "status": status,
                "stage": "identity matching",
                "subject": row.get("identity_label", ""),
                "image_id": row.get("image_id", ""),
                "path": row.get("path", ""),
                "expected": row.get("identity_id", ""),
                "actual": row.get("top1_identity_id", ""),
                "score": row.get("top1_score", ""),
                "reason": reason,
            }
        )
    return rows


def group_case_review_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    case_rows: list[dict[str, Any]] = []
    for row in rows:
        recall = float(row.get("visible_face_recall") or 0)
        error = row.get("error", "")
        contract_errors = int(row.get("contract_errors") or 0)
        if error or contract_errors:
            status = "FAIL"
            reason = error or f"{contract_errors} contract errors"
        elif recall >= 1:
            status = "PASS"
            reason = "expected visible faces detected"
        elif recall > 0:
            status = "PARTIAL"
            reason = "some expected visible faces were missed"
        else:
            status = "FAIL"
            reason = "no expected visible faces detected"
        case_rows.append(
            {
                "status": status,
                "stage": "group face count",
                "subject": row.get("cohort", ""),
                "image_id": row.get("photo_id", ""),
                "path": row.get("path", ""),
                "expected": row.get("expected_visible_faces", ""),
                "actual": row.get("faces_detected", ""),
                "score": row.get("visible_face_recall", ""),
                "reason": reason,
            }
        )
    return case_rows


def wider_case_review_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    case_rows: list[dict[str, Any]] = []
    for row in rows:
        error = row.get("error", "")
        contract_errors = int(row.get("contract_errors") or 0)
        false_negatives = int(row.get("false_negatives") or 0)
        false_positives = int(row.get("false_positives") or 0)
        matched = int(row.get("matched_faces") or 0)
        if error or contract_errors:
            status = "FAIL"
            reason = error or f"{contract_errors} contract errors"
        elif false_negatives == 0 and false_positives == 0:
            status = "PASS"
            reason = "all labeled boxes matched with no extra detections"
        elif matched > 0:
            status = "PARTIAL"
            reason = f"{false_negatives} missed, {false_positives} extra"
        else:
            status = "FAIL"
            reason = "no labeled boxes matched"
        case_rows.append(
            {
                "status": status,
                "stage": "bbox detection",
                "subject": row.get("event", ""),
                "image_id": row.get("image_id", ""),
                "path": row.get("path", ""),
                "expected": row.get("ground_truth_faces", ""),
                "actual": row.get("predicted_faces", ""),
                "score": row.get("bbox_recall", ""),
                "reason": reason,
            }
        )
    return case_rows


def run_identity_eval(
    manifest: dict[str, Any],
    manifest_path: Path,
    config: dict[str, Any],
    run_dir: Path,
    ai_url: str,
    run_id: str,
    limit_identities: int | None,
) -> dict[str, Any]:
    dataset_root = Path(manifest["dataset"]["root"]).expanduser().resolve()
    threshold = float(config.get("face_match_threshold", os.getenv("FACE_MATCH_THRESHOLD", "0.68")))
    identities = manifest["identities"][: limit_identities or len(manifest["identities"])]

    all_rows: list[dict[str, Any]] = []
    failed_cases: list[dict[str, Any]] = []
    extraction_rows: list[dict[str, Any]] = []
    latencies: list[float] = []
    contract_errors = 0
    failed_images = 0
    detected_images = 0
    gallery_vectors: dict[str, list[dict[str, Any]]] = {}
    probe_records: list[dict[str, Any]] = []

    for identity in identities:
        for image in identity["images"]:
            path = dataset_root / image["path"]
            quality = image_quality(path)
            row: dict[str, Any] = {
                "identity_id": identity["identity_id"],
                "identity_label": identity["label"],
                "image_id": image["image_id"],
                "split": image["split"],
                "path": path.as_posix(),
                "path_hint": image_sha_hint(path),
                "quality_tags": "|".join(quality["tags"]),
                "brightness": quality["brightness"],
                "sharpness": quality["sharpness"],
            }
            try:
                with Image.open(path) as source:
                    width, height = source.size
                result = extract_faces(path, ai_url, f"eval-{run_id}-{image['image_id']}")
                latency = float(result.get("processing_ms") or 0)
                latencies.append(latency)
                faces = result.get("faces", [])
                face = primary_face(faces)
                row.update(
                    {
                        "faces_detected": len(faces),
                        "processing_ms": latency,
                        "request_id": result.get("request_id"),
                    }
                )
                if face is None:
                    failed_images += 1
                    failed_cases.append(
                        {
                            "reason": "no_face_detected",
                            "identity": identity["label"],
                            "image_id": image["image_id"],
                            "path": path.as_posix(),
                            "expected": "one face",
                            "actual": "zero faces",
                        }
                    )
                    all_rows.append(row)
                    extraction_rows.append(row)
                    continue

                errors = validate_face(face, width, height)
                contract_errors += len(errors)
                if errors:
                    failed_cases.append(
                        {
                            "reason": "; ".join(errors),
                            "identity": identity["label"],
                            "image_id": image["image_id"],
                            "path": path.as_posix(),
                            "expected": "valid bbox and 512-d embedding",
                            "actual": "contract error",
                        }
                    )
                embedding = normalize([float(value) for value in face["embedding"]])
                x1, y1, x2, y2 = [int(value) for value in face["bbox"]]
                face_area_ratio = ((x2 - x1) * (y2 - y1)) / max(1, width * height)
                face_size_tag = (
                    "small_face" if face_area_ratio < 0.04 else "large_face" if face_area_ratio > 0.25 else "medium_face"
                )
                tags = quality["tags"] + [face_size_tag]
                row.update(
                    {
                        "bbox": json.dumps([x1, y1, x2, y2]),
                        "embedding_dimensions": len(embedding),
                        "embedding_norm": round(math.sqrt(sum(value * value for value in embedding)), 6),
                        "face_area_ratio": round(face_area_ratio, 6),
                        "quality_tags": "|".join(tags),
                    }
                )
                if config.get("save_embeddings", False):
                    row["embedding"] = json.dumps(embedding)

                detected_images += 1
                record = {**row, "embedding_vector": embedding, "tags": tags}
                if image["split"] == "gallery":
                    gallery_vectors.setdefault(identity["identity_id"], []).append(record)
                else:
                    probe_records.append(record)
                all_rows.append(row)
                extraction_rows.append(row)
            except Exception as error:
                failed_images += 1
                row["error"] = str(error)
                failed_cases.append(
                    {
                        "reason": "extraction_failed",
                        "identity": identity["label"],
                        "image_id": image["image_id"],
                        "path": path.as_posix(),
                        "expected": "AI extraction response",
                        "actual": str(error),
                    }
                )
                all_rows.append(row)
                extraction_rows.append(row)

    prediction_rows: list[dict[str, Any]] = []
    condition_buckets: dict[str, list[dict[str, Any]]] = {}
    genuine_scores: list[float] = []
    impostor_scores: list[float] = []
    top1_correct = 0
    top5_correct = 0
    verified_top1_correct = 0
    top1_false_accepts = 0
    false_rejects = 0
    total_impostor_comparisons = 0
    false_accept_comparisons = 0
    evaluated_probes = 0

    for probe in probe_records:
        true_id = probe["identity_id"]
        scores = []
        for identity_id, vectors in gallery_vectors.items():
            if not vectors:
                continue
            best_score = max(cosine(probe["embedding_vector"], vector["embedding_vector"]) for vector in vectors)
            scores.append((identity_id, best_score))
        scores.sort(key=lambda item: item[1], reverse=True)
        if not scores:
            failed_cases.append(
                {
                    "reason": "no_gallery_available",
                    "identity": probe["identity_label"],
                    "image_id": probe["image_id"],
                    "path": probe["path"],
                    "expected": "gallery embeddings",
                    "actual": "none",
                }
            )
            continue

        evaluated_probes += 1
        score_map = dict(scores)
        genuine_score = score_map.get(true_id)
        if genuine_score is not None:
            genuine_scores.append(genuine_score)
        for identity_id, score in scores:
            if identity_id != true_id:
                impostor_scores.append(score)
                total_impostor_comparisons += 1
                if score >= threshold:
                    false_accept_comparisons += 1

        top1_id, top1_score = scores[0]
        top5 = [identity_id for identity_id, _ in scores[:5]]
        is_top1 = top1_id == true_id
        is_top5 = true_id in top5
        is_verified = is_top1 and top1_score >= threshold
        top1_correct += int(is_top1)
        top5_correct += int(is_top5)
        verified_top1_correct += int(is_verified)
        if not is_verified:
            false_rejects += 1
        if top1_id != true_id and top1_score >= threshold:
            top1_false_accepts += 1

        prediction = {
            "image_id": probe["image_id"],
            "identity_id": true_id,
            "identity_label": probe["identity_label"],
            "path": probe["path"],
            "top1_identity_id": top1_id,
            "top1_score": round(top1_score, 6),
            "genuine_score": round(genuine_score, 6) if genuine_score is not None else "",
            "top1_correct": is_top1,
            "top5_correct": is_top5,
            "verified_at_threshold": is_verified,
            "threshold": threshold,
            "quality_tags": probe["quality_tags"],
        }
        prediction_rows.append(prediction)

        if not is_verified:
            failed_cases.append(
                {
                    "reason": "not_verified_at_threshold",
                    "identity": probe["identity_label"],
                    "image_id": probe["image_id"],
                    "path": probe["path"],
                    "expected": true_id,
                    "actual": top1_id,
                    "score": round(top1_score, 6),
                }
            )
        for tag in probe["tags"]:
            condition_buckets.setdefault(tag, []).append(prediction)

    condition_rows = []
    for tag, rows in sorted(condition_buckets.items()):
        condition_rows.append(
            {
                "condition": tag,
                "probe_images": len(rows),
                "top1_accuracy": round(sum(row["top1_correct"] for row in rows) / len(rows), 6),
                "verified_top1_accuracy": round(
                    sum(row["verified_at_threshold"] for row in rows) / len(rows), 6
                ),
            }
        )

    sweep_rows, eer = threshold_sweep(genuine_scores, impostor_scores)
    total_images = sum(len(identity["images"]) for identity in identities)
    gallery_images = sum(
        1 for identity in identities for image in identity["images"] if image["split"] == "gallery"
    )
    probe_images = sum(
        1 for identity in identities for image in identity["images"] if image["split"] == "probe"
    )
    contract_denominator = max(1, detected_images)
    metrics = {
        "run": {
            "id": run_id,
            "profile": config["profile"],
            "manifest": relative(manifest_path),
            "ai_service_url": ai_url,
            "started_at": datetime.now().astimezone().isoformat(),
        },
        "dataset": {
            "kind": "identity-face-eval",
            "name": manifest["dataset"].get("name"),
            "identities": len(identities),
            "images": total_images,
            "gallery_images": gallery_images,
            "probe_images": probe_images,
            "min_identities": len(identities),
            "min_gallery_images": gallery_images,
            "min_probe_images": probe_images,
        },
        "detection": {
            "success_rate": round(detected_images / max(1, total_images), 6),
            "detected_images": detected_images,
            "failed_images": failed_images,
            "min_success_rate": round(detected_images / max(1, total_images), 6),
        },
        "embedding": {
            "contract_errors": contract_errors,
            "contract_error_rate": round(contract_errors / contract_denominator, 6),
            "max_contract_error_rate": round(contract_errors / contract_denominator, 6),
        },
        "recognition": {
            "evaluated_probe_images": evaluated_probes,
            "top1_accuracy": round(top1_correct / max(1, probe_images), 6),
            "top5_accuracy": round(top5_correct / max(1, probe_images), 6),
            "verified_top1_accuracy": round(verified_top1_correct / max(1, probe_images), 6),
            "false_accept_rate": round(false_accept_comparisons / max(1, total_impostor_comparisons), 6),
            "top1_false_accept_rate": round(top1_false_accepts / max(1, probe_images), 6),
            "false_reject_rate": round(false_rejects / max(1, probe_images), 6),
            "equal_error_rate": eer,
            "min_top1_accuracy": round(top1_correct / max(1, probe_images), 6),
            "min_verified_top1_accuracy": round(verified_top1_correct / max(1, probe_images), 6),
            "max_false_accept_rate": round(false_accept_comparisons / max(1, total_impostor_comparisons), 6),
            "max_false_reject_rate": round(false_rejects / max(1, probe_images), 6),
            "max_equal_error_rate": eer,
        },
        "latency": {
            "mean_processing_ms": round(sum(latencies) / len(latencies), 2) if latencies else None,
            "p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
            "max_processing_ms": round(max(latencies), 2) if latencies else None,
            "max_p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
        },
        "system": {
            "failed_images": failed_images,
            "max_failed_images": failed_images,
        },
    }

    write_csv(run_dir / "extractions.csv", extraction_rows)
    write_csv(run_dir / "probe-predictions.csv", prediction_rows)
    write_csv(run_dir / "condition-metrics.csv", condition_rows)
    write_csv(run_dir / "threshold-sweep.csv", sweep_rows)
    write_case_review(
        run_dir / "case-review",
        identity_case_review_rows(extraction_rows, prediction_rows),
        "Identity Face Evaluation Case Review",
    )
    write_failed_cases_html(run_dir / "failed-cases.html", failed_cases[:1000])
    write_json(run_dir / "failed-cases.json", failed_cases)
    return metrics


def run_group_eval(
    manifest: dict[str, Any],
    manifest_path: Path,
    config: dict[str, Any],
    run_dir: Path,
    ai_url: str,
    run_id: str,
    limit_photos: int | None,
) -> dict[str, Any]:
    fixture_root = manifest_path.parent
    rows: list[dict[str, Any]] = []
    failed_cases: list[dict[str, Any]] = []
    latencies: list[float] = []
    contract_errors = 0
    failed_images = 0

    entries = manifest["photos"][: limit_photos or len(manifest["photos"])]

    for entry in entries:
        path = fixture_root / "photos" / entry["filename"]
        row = {
            "photo_id": entry["id"],
            "cohort": entry.get("cohort"),
            "variant": entry.get("variant"),
            "path": relative(path),
            "expected_visible_faces": entry["expected_visible_faces"],
        }
        try:
            with Image.open(path) as source:
                width, height = source.size
            result = extract_faces(path, ai_url, f"eval-{run_id}-{entry['id']}")
            faces = result.get("faces", [])
            latency = float(result.get("processing_ms") or 0)
            latencies.append(latency)
            errors: list[str] = []
            for face in faces:
                errors.extend(validate_face(face, width, height))
            contract_errors += len(errors)
            detected = len(faces)
            expected = int(entry["expected_visible_faces"])
            recall = min(detected, expected) / max(1, expected)
            row.update(
                {
                    "faces_detected": detected,
                    "visible_face_recall": round(recall, 6),
                    "processing_ms": latency,
                    "contract_errors": len(errors),
                }
            )
            if errors:
                failed_cases.append(
                    {
                        "reason": "; ".join(errors),
                        "identity": entry.get("cohort", ""),
                        "image_id": entry["id"],
                        "path": relative(path),
                        "expected": "valid extracted faces",
                        "actual": "contract error",
                    }
                )
        except Exception as error:
            failed_images += 1
            row["error"] = str(error)
            row.update(
                {
                    "faces_detected": 0,
                    "visible_face_recall": 0,
                    "contract_errors": 0,
                }
            )
            failed_cases.append(
                {
                    "reason": "extraction_failed",
                    "identity": entry.get("cohort", ""),
                    "image_id": entry["id"],
                    "path": relative(path),
                    "expected": "AI extraction response",
                    "actual": str(error),
                }
            )
        rows.append(row)

    mean_recall = statistics.mean(row.get("visible_face_recall", 0) for row in rows)
    metrics = {
        "run": {
            "id": run_id,
            "profile": config["profile"],
            "manifest": relative(manifest_path),
            "ai_service_url": ai_url,
            "started_at": datetime.now().astimezone().isoformat(),
        },
        "dataset": {
            "kind": "group-e2e",
            "photos": len(rows),
            "min_photos": len(rows),
        },
        "detection": {
            "visible_face_recall": round(mean_recall, 6),
            "min_visible_face_recall": round(mean_recall, 6),
        },
        "embedding": {
            "contract_errors": contract_errors,
            "contract_error_rate": round(contract_errors / max(1, sum(row.get("faces_detected", 0) for row in rows)), 6),
            "max_contract_error_rate": round(contract_errors / max(1, sum(row.get("faces_detected", 0) for row in rows)), 6),
        },
        "latency": {
            "mean_processing_ms": round(sum(latencies) / len(latencies), 2) if latencies else None,
            "p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
            "max_processing_ms": round(max(latencies), 2) if latencies else None,
            "max_p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
        },
        "system": {
            "failed_images": failed_images,
            "max_failed_images": failed_images,
        },
    }
    write_csv(run_dir / "group-detection-summary.csv", rows)
    write_case_review(run_dir / "case-review", group_case_review_rows(rows), "Group Photo Evaluation Case Review")
    write_failed_cases_html(run_dir / "failed-cases.html", failed_cases)
    write_json(run_dir / "failed-cases.json", failed_cases)
    return metrics


def run_wider_detection_eval(
    manifest: dict[str, Any],
    manifest_path: Path,
    config: dict[str, Any],
    run_dir: Path,
    ai_url: str,
    run_id: str,
    limit_photos: int | None,
) -> dict[str, Any]:
    dataset_root = Path(manifest["dataset"]["root"]).expanduser().resolve()
    iou_threshold = float(config.get("iou_threshold", 0.5))
    entries = manifest["images"][: limit_photos or len(manifest["images"])]

    rows: list[dict[str, Any]] = []
    failed_cases: list[dict[str, Any]] = []
    latencies: list[float] = []
    contract_errors = 0
    failed_images = 0
    total_ground_truth = 0
    total_predicted = 0
    total_matched = 0

    for entry in entries:
        path = dataset_root / entry["path"]
        gt_boxes = [[int(value) for value in face["bbox"]] for face in entry["ground_truth_faces"]]
        total_ground_truth += len(gt_boxes)
        row: dict[str, Any] = {
            "image_id": entry["image_id"],
            "split": entry["split"],
            "event": entry.get("event", ""),
            "path": path.as_posix(),
            "ground_truth_faces": len(gt_boxes),
            "ground_truth_bboxes": json.dumps(gt_boxes),
        }
        try:
            with Image.open(path) as source:
                width, height = source.size
            result = extract_faces(path, ai_url, f"eval-{run_id}-{entry['image_id']}")
            faces = result.get("faces", [])
            latency = float(result.get("processing_ms") or 0)
            latencies.append(latency)

            predicted_boxes = []
            image_contract_errors: list[str] = []
            for face in faces:
                errors = validate_face(face, width, height)
                image_contract_errors.extend(errors)
                bbox = face.get("bbox")
                if isinstance(bbox, list) and len(bbox) == 4 and not errors:
                    predicted_boxes.append([int(value) for value in bbox])

            contract_errors += len(image_contract_errors)
            total_predicted += len(predicted_boxes)
            matched, matches = match_bboxes(predicted_boxes, gt_boxes, iou_threshold)
            total_matched += matched
            false_negatives = max(0, len(gt_boxes) - matched)
            false_positives = max(0, len(predicted_boxes) - matched)
            precision = matched / max(1, len(predicted_boxes))
            recall = matched / max(1, len(gt_boxes))
            count_error = abs(len(predicted_boxes) - len(gt_boxes))
            exact_count_match = len(predicted_boxes) == len(gt_boxes)

            row.update(
                {
                    "predicted_faces": len(predicted_boxes),
                    "predicted_bboxes": json.dumps(predicted_boxes),
                    "matched_faces": matched,
                    "false_negatives": false_negatives,
                    "false_positives": false_positives,
                    "bbox_precision": round(precision, 6),
                    "bbox_recall": round(recall, 6),
                    "absolute_count_error": count_error,
                    "exact_count_match": exact_count_match,
                    "match_ious": json.dumps([round(iou, 6) for _, _, iou in matches]),
                    "processing_ms": latency,
                    "contract_errors": len(image_contract_errors),
                }
            )
            if image_contract_errors:
                failed_cases.append(
                    {
                        "reason": "; ".join(image_contract_errors),
                        "identity": entry.get("event", ""),
                        "image_id": entry["image_id"],
                        "path": path.as_posix(),
                        "expected": "valid bbox and 512-d embedding",
                        "actual": "contract error",
                    }
                )
            if false_negatives:
                failed_cases.append(
                    {
                        "reason": "missed_ground_truth_faces",
                        "identity": entry.get("event", ""),
                        "image_id": entry["image_id"],
                        "path": path.as_posix(),
                        "expected": len(gt_boxes),
                        "actual": len(predicted_boxes),
                        "score": round(recall, 6),
                    }
                )
            if false_positives:
                failed_cases.append(
                    {
                        "reason": "extra_face_detections",
                        "identity": entry.get("event", ""),
                        "image_id": entry["image_id"],
                        "path": path.as_posix(),
                        "expected": len(gt_boxes),
                        "actual": len(predicted_boxes),
                        "score": round(precision, 6),
                    }
                )
        except Exception as error:
            failed_images += 1
            row["error"] = str(error)
            row.update(
                {
                    "predicted_faces": 0,
                    "matched_faces": 0,
                    "false_negatives": len(gt_boxes),
                    "false_positives": 0,
                    "bbox_precision": 0,
                    "bbox_recall": 0,
                    "absolute_count_error": len(gt_boxes),
                    "exact_count_match": False,
                    "contract_errors": 0,
                }
            )
            failed_cases.append(
                {
                    "reason": "extraction_failed",
                    "identity": entry.get("event", ""),
                    "image_id": entry["image_id"],
                    "path": path.as_posix(),
                    "expected": "AI extraction response",
                    "actual": str(error),
                }
            )
        rows.append(row)

    precision = total_matched / max(1, total_predicted)
    recall = total_matched / max(1, total_ground_truth)
    f1 = (2 * precision * recall / (precision + recall)) if precision + recall else 0
    count_errors = [float(row.get("absolute_count_error", 0)) for row in rows]
    exact_count_accuracy = sum(bool(row.get("exact_count_match")) for row in rows) / max(1, len(rows))
    contract_denominator = max(1, total_predicted)
    metrics = {
        "run": {
            "id": run_id,
            "profile": config["profile"],
            "manifest": relative(manifest_path),
            "ai_service_url": ai_url,
            "started_at": datetime.now().astimezone().isoformat(),
        },
        "dataset": {
            "kind": "wider-face-detection-eval",
            "name": manifest["dataset"].get("name"),
            "images": len(rows),
            "ground_truth_faces": total_ground_truth,
            "min_images": len(rows),
            "min_ground_truth_faces": total_ground_truth,
        },
        "detection": {
            "iou_threshold": iou_threshold,
            "predicted_faces": total_predicted,
            "matched_faces": total_matched,
            "false_negatives": max(0, total_ground_truth - total_matched),
            "false_positives": max(0, total_predicted - total_matched),
            "bbox_precision": round(precision, 6),
            "bbox_recall": round(recall, 6),
            "bbox_f1": round(f1, 6),
            "exact_count_accuracy": round(exact_count_accuracy, 6),
            "count_mae": round(statistics.mean(count_errors), 6) if count_errors else None,
            "min_bbox_precision": round(precision, 6),
            "min_bbox_recall": round(recall, 6),
            "min_exact_count_accuracy": round(exact_count_accuracy, 6),
            "max_count_mae": round(statistics.mean(count_errors), 6) if count_errors else None,
        },
        "embedding": {
            "contract_errors": contract_errors,
            "contract_error_rate": round(contract_errors / contract_denominator, 6),
            "max_contract_error_rate": round(contract_errors / contract_denominator, 6),
        },
        "latency": {
            "mean_processing_ms": round(sum(latencies) / len(latencies), 2) if latencies else None,
            "p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
            "max_processing_ms": round(max(latencies), 2) if latencies else None,
            "max_p95_processing_ms": round(percentile(latencies, 0.95) or 0, 2) if latencies else None,
        },
        "system": {
            "failed_images": failed_images,
            "max_failed_images": failed_images,
        },
    }

    write_csv(run_dir / "wider-detection-summary.csv", rows)
    write_case_review(run_dir / "case-review", wider_case_review_rows(rows), "WIDER FACE Bbox Case Review")
    write_failed_cases_html(run_dir / "failed-cases.html", failed_cases[:1000])
    write_json(run_dir / "failed-cases.json", failed_cases)
    return metrics


