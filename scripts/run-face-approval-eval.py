def image_quality(path: Path) -> dict[str, Any]:
    with Image.open(path) as image:
        gray = image.convert("L").resize((128, 128))
        pixels = list(gray.tobytes())
    brightness = statistics.mean(pixels)
    diffs: list[int] = []
    width = 128
    for index, value in enumerate(pixels):
        if index % width != width - 1:
            diffs.append((value - pixels[index + 1]) ** 2)
        if index + width < len(pixels):
            diffs.append((value - pixels[index + width]) ** 2)
    sharpness = statistics.mean(diffs) if diffs else 0
    tags = []
    if brightness < 70:
        tags.append("low_light")
    elif brightness > 190:
        tags.append("bright_light")
    else:
        tags.append("normal_light")
    tags.append("soft_or_blur" if sharpness < 80 else "sharp")
    return {
        "brightness": round(brightness, 2),
        "sharpness": round(sharpness, 2),
        "tags": tags,
    }


def validate_face(face: dict[str, Any], width: int, height: int) -> list[str]:
    errors: list[str] = []
    bbox = face.get("bbox")
    embedding = face.get("embedding")
    if not isinstance(bbox, list) or len(bbox) != 4:
        errors.append("bbox must contain four coordinates")
    else:
        x1, y1, x2, y2 = [int(value) for value in bbox]
        if not (0 <= x1 < x2 <= width and 0 <= y1 < y2 <= height):
            errors.append(f"bbox outside image bounds: {bbox}")
    if not isinstance(embedding, list) or len(embedding) != 512:
        errors.append("embedding must contain 512 values")
    elif not all(isinstance(value, (int, float)) and math.isfinite(value) for value in embedding):
        errors.append("embedding contains a non-finite value")
    return errors


def bbox_iou(left: list[int], right: list[int]) -> float:
    left_x1, left_y1, left_x2, left_y2 = left
    right_x1, right_y1, right_x2, right_y2 = right
    inter_x1 = max(left_x1, right_x1)
    inter_y1 = max(left_y1, right_y1)
    inter_x2 = min(left_x2, right_x2)
    inter_y2 = min(left_y2, right_y2)
    inter_width = max(0, inter_x2 - inter_x1)
    inter_height = max(0, inter_y2 - inter_y1)
    intersection = inter_width * inter_height
    left_area = max(0, left_x2 - left_x1) * max(0, left_y2 - left_y1)
    right_area = max(0, right_x2 - right_x1) * max(0, right_y2 - right_y1)
    union = left_area + right_area - intersection
    return intersection / union if union else 0


def match_bboxes(
    predicted: list[list[int]],
    ground_truth: list[list[int]],
    iou_threshold: float,
) -> tuple[int, list[tuple[int, int, float]]]:
    pairs = []
    for predicted_index, predicted_box in enumerate(predicted):
        for gt_index, gt_box in enumerate(ground_truth):
            iou = bbox_iou(predicted_box, gt_box)
            if iou >= iou_threshold:
                pairs.append((predicted_index, gt_index, iou))
    pairs.sort(key=lambda item: item[2], reverse=True)

    used_predicted: set[int] = set()
    used_gt: set[int] = set()
    matches: list[tuple[int, int, float]] = []
    for predicted_index, gt_index, iou in pairs:
        if predicted_index in used_predicted or gt_index in used_gt:
            continue
        used_predicted.add(predicted_index)
        used_gt.add(gt_index)
        matches.append((predicted_index, gt_index, iou))
    return len(matches), matches


def primary_face(faces: list[dict[str, Any]]) -> dict[str, Any] | None:
    if not faces:
        return None

    def area(face: dict[str, Any]) -> int:
        x1, y1, x2, y2 = [int(value) for value in face.get("bbox", [0, 0, 0, 0])]
        return max(0, x2 - x1) * max(0, y2 - y1)

    return max(faces, key=area)


def extract_faces(path: Path, ai_url: str, request_id: str) -> dict[str, Any]:
    with path.open("rb") as handle:
        response = requests.post(
            f"{ai_url}/internal/face/extract",
            files={"file": (path.name, handle, "image/jpeg")},
            headers={"x-request-id": request_id},
            timeout=IMAGE_TIMEOUT_SECONDS,
        )
    response.raise_for_status()
    return response.json()


